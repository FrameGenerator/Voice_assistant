# УНИВЕРСАЛЬНАЯ ФУНКЦИЯ ПОИСКА И ИНИЦИАЛИЗАЦИИ
# =====================================================================
def get_cmd(text_start, data_words):
    """Определение команды из словаря"""
    user_words = set(text_start.lower().strip().split())
    for cmd, words_set in data_words.items():
        if user_words & words_set:
            return cmd
    return None


